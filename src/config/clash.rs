/// iOS-friendly Clash/Mihomo config:
///  - no dns.listen (iOS VPN extension sandbox forbids socket binds)
///  - redir-host instead of fake-ip (more reliable inside the extension)
///  - no external-controller / external-ui / allow-lan / bind-address (sandbox)
///  - rule-providers trimmed to 3 essentials (gfw + cncidr + proxy) to stay
///    under iOS's 50 MB VPN-extension memory cap.
