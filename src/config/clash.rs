use crate::cli::ClientConfigArgs;
use anyhow::Result;
use colored::Colorize;
use std::fs;

pub async fn run(args: ClientConfigArgs) -> Result<()> {
    let yaml = if args.cfw {
        build_clash_yaml_cfw(&args.host, &args.uuid, args.cdn_host.as_deref())
    } else if args.ios_minimal {
        build_clash_yaml_ios_minimal(
            &args.uuid, args.cdn_host.as_deref(),
        )
    } else if args.ios {
        build_clash_yaml_ios(
            &args.host, args.vless_port, args.hy2_port,
            &args.sni, &args.uuid,
            &args.hy2_password, &args.reality_public_key, &args.reality_short_id,
            args.cdn_host.as_deref(),
        )
    } else {
        build_clash_yaml(
            &args.host, args.vless_port, args.hy2_port,
            &args.sni, &args.uuid,
            &args.hy2_password, &args.reality_public_key, &args.reality_short_id,
            args.cdn_host.as_deref(),
        )
    };

    match args.output {
        Some(ref path) => {
            fs::write(path, &yaml)?;
            println!("{}", format!("✓ Clash config written to {path}").green());
        }
        None => print!("{yaml}"),
    }

    Ok(())
}

